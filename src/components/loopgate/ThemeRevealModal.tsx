export function pickAutoTheme(seed: string): { theme: string; info: string } {
  let hash = 0;
  for (let i = 0; i < seed.length; i++) hash = (hash * 31 + seed.charCodeAt(i)) >>> 0;
  return AUTO_THEMES[hash % AUTO_THEMES.length];
}